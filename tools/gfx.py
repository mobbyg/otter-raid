#!/usr/bin/env python3
"""Otter Raid graphics compiler.

Reads the hand-editable text art under gfx/ and writes the C64 data
files under c64/gfx/ plus PNG/GIF previews under build/gfx_preview/.

    python3 tools/gfx.py            # or: make assets
    python3 tools/gfx.py --no-preview

Source format (see docs/c64-graphics.md for the full description):

    ; comment (anything after ';' is ignored)
    @kind [NAME] key=value ...
    <pixel rows>

Pixel alphabets
    game chars / stamps (multicolor): . water  w light blue  b brown
                                      g green  - transparent (stamps)
    text chars (hires):               . off    # on
    multicolor sprites:               . clear  k black  c own colour
                                      w white
    hires sprites:                    . clear  x own colour

Output is fully deterministic: running twice gives identical files.
"""
