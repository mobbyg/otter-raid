class Screen:
    """A playfield of char codes, rendered with the game charset."""

    def __init__(self, g, cols, rows):
        self.g = g
        self.cols, self.rows = cols, rows
        self.cell = np.zeros((rows, cols), dtype=np.int16)
        self.kind = np.zeros((rows, cols), dtype=np.int8)  # 0 w 1 l 2 e

    def put_stamp(self, idx, cx, cy):
        s = self.g.stamps[idx]
        for k, code in enumerate(s["codes"]):
            x, y = cx + k % s["w"], cy + k // s["w"]
            if code != STAMP_TRANSPARENT and 0 <= x < self.cols \
                    and 0 <= y < self.rows:
                self.cell[y, x] = code
                self.kind[y, x] = 3

    def render(self, water_frame=0, craw_frame=0, rows=None):
        g = self.g
        charset = list(g.game)
        wf = g.water_frames[water_frame % len(g.water_frames)]
        for i in range(8):
            charset[i] = pack_mc_char(wf[i])
        cf = g.crawfish_frames[craw_frame % len(g.crawfish_frames)]
        for i in range(2):
            charset[CRAWFISH_FIRST + i] = pack_mc_char(cf[i])
        ff = g.fish_frames[craw_frame % len(g.fish_frames)]
        for i in range(2):
            charset[FISH_FIRST + i] = pack_mc_char(ff[i])
        gf = g.gift_frames[(craw_frame // 2) % len(g.gift_frames)]
        for i in range(2 * GIFT_KINDS):
            charset[GIFT_FIRST + i] = pack_mc_char(gf[i])
        cache = {}
        a = np.zeros((self.rows * 8, self.cols * 8), dtype=np.int16)
        for y in range(self.rows):
            for x in range(self.cols):
                c = int(self.cell[y, x])
                if c not in cache:
                    cache[c] = mc_char_img(charset[c])
                a[y * 8:y * 8 + 8, x * 8:x * 8 + 8] = cache[c]
        return a


