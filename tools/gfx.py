def byte_lines(data, per=8, comment=None):
    lines = []
    for i in range(0, len(data), per):
        chunk = ",".join(f"${v:02X}" for v in data[i:i + per])
        s = f"\t.byte {chunk}"
        if comment and i == 0:
            if len(s.expandtabs(8)) + len(comment) + 4 <= 80:
                s += f"  ; {comment}"
            else:
                lines.append(f"; {comment}")
        lines.append(s)
    return lines


def check_lines(text, fname):
    for i, ln in enumerate(text.splitlines(), 1):
        if len(ln.expandtabs(8)) > 80:
            raise GfxError(f"{fname}:{i}: line longer than 80 chars")


def write_text(path, text):
    check_lines(text, path.name)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


