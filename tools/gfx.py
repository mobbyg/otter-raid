def rgb(idx_img, bg=None):
    """Palette-index array (-1 transparent) -> RGB uint8 array."""
    pal = np.array(PALETTE, dtype=np.uint8)
    arr = np.asarray(idx_img)
    out = pal[np.clip(arr, 0, 15)]
    if bg is not None:
        out[arr < 0] = PALETTE[bg]
    return out


def save_png(arr_rgb, path, scale=3):
    img = Image.fromarray(np.ascontiguousarray(arr_rgb), "RGB")
    if scale != 1:
        img = img.resize((img.width * scale, img.height * scale),
                         Image.NEAREST)
    img.save(path, optimize=False)


def mc_char_img(data, colors=GAME_COLORS):
    """8 bytes -> 8x8 palette-index array (2 px wide MC pixels)."""
    a = np.zeros((8, 8), dtype=np.int16)
    for y, row in enumerate(unpack_mc_char(data)):
        for x, v in enumerate(row):
            a[y, 2 * x:2 * x + 2] = colors[v]
    return a


def hr_char_img(data, fg=WHITE, bg=BLACK):
    a = np.zeros((8, 8), dtype=np.int16)
    for y, row in enumerate(unpack_hr_char(data)):
        for x, v in enumerate(row):
            a[y, x] = fg if v else bg
    return a


def sprite_img(s, color=None):
    """Sprite -> 21x24 palette-index array (-1 transparent)."""
    col = s["color"] if color is None else color
    a = np.full((21, 24), -1, dtype=np.int16)
    if s["mode"] == "mc":
        cmap = {0: -1, 1: BLACK, 2: col, 3: WHITE}
        for y, row in enumerate(s["pix"]):
            for x, v in enumerate(row):
                a[y, 2 * x:2 * x + 2] = cmap[v]
    else:
        for y, row in enumerate(s["pix"]):
            for x, v in enumerate(row):
                if v:
                    a[y, x] = col
    return a


def expand(a, ex, ey):
    if ex:
        a = np.repeat(a, 2, axis=1)
    if ey:
        a = np.repeat(a, 2, axis=0)
    return a


def blit(dst, src, x, y):
    """Blit palette-index src (with -1 transparency) into dst."""
    h, w = src.shape
    H, W = dst.shape
    x0, y0 = max(0, x), max(0, y)
    x1, y1 = min(W, x + w), min(H, y + h)
    if x0 >= x1 or y0 >= y1:
        return
    s = src[y0 - y:y1 - y, x0 - x:x1 - x]
    d = dst[y0:y1, x0:x1]
    m = s >= 0
    d[m] = s[m]


def label_font():
    try:
        return ImageFont.load_default()
    except Exception:
        return None


def draw_labels(img, labels, scale):
    """labels: list of (x, y, text) in unscaled pixel coords."""
    d = ImageDraw.Draw(img)
    f = label_font()
    for x, y, t in labels:
        d.text((x * scale, y * scale), t, fill=(230, 230, 230), font=f)


def sheet_png(cells, cols, cw, ch, path, scale=3, label_h=10,
              bg=(24, 24, 24)):
    """cells: list of (rgb array, label)."""
    rows = (len(cells) + cols - 1) // cols
    W = cols * (cw + 4) * scale
    H = rows * (ch + 4) * scale + rows * label_h
    img = Image.new("RGB", (W, H), bg)
    d = ImageDraw.Draw(img)
    f = label_font()
    for i, (arr, lab) in enumerate(cells):
        cx, cy = i % cols, i // cols
        x = cx * (cw + 4) * scale + 2 * scale
        y = cy * ((ch + 4) * scale + label_h) + 2 * scale
        im = Image.fromarray(np.ascontiguousarray(arr), "RGB")
        im = im.resize((im.width * scale, im.height * scale),
                       Image.NEAREST)
        img.paste(im, (x, y))
        if lab:
            d.text((x, y + ch * scale + 2), lab, fill=(220, 220, 220),
                   font=f)
    img.save(path, optimize=False)


def save_gif(frames_rgb, path, delay, scale=3):
    ims = []
    for a in frames_rgb:
        im = Image.fromarray(np.ascontiguousarray(a), "RGB")
        im = im.resize((im.width * scale, im.height * scale),
                       Image.NEAREST)
        ims.append(im.convert("P", palette=Image.ADAPTIVE, colors=64))
    ims[0].save(path, save_all=True, append_images=ims[1:],
                duration=delay, loop=0, disposal=1, optimize=False)


def char_sheet(chars_img, labels=True):
    """16x16 sheet with 1px gaps; chars_img: list of 256 8x8 rgb."""
    gap = 2
    W = 16 * (8 + gap) + gap
    out = np.full((W, W, 3), 40, dtype=np.uint8)
    for c in range(256):
        x = gap + (c % 16) * (8 + gap)
        y = gap + (c // 16) * (8 + gap)
        out[y:y + 8, x:x + 8] = chars_img[c]
    return out


