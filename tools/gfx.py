def frame_box(g, cols, rows, color):
    """Return a cols x rows list of (code,color) using frame glyphs."""
    tl, tr = tx(g, "FRAME_TL"), tx(g, "FRAME_TR")
    bl, br = tx(g, "FRAME_BL"), tx(g, "FRAME_BR")
    hz_t, hz_b = tx(g, "FRAME_TOP"), tx(g, "FRAME_BOTTOM")
    vl, vr = tx(g, "FRAME_LEFT"), tx(g, "FRAME_RIGHT")
    out = []
    for y in range(rows):
        ln = []
        for x in range(cols):
            if y == 0:
                c = tl if x == 0 else tr if x == cols - 1 else hz_t
            elif y == rows - 1:
                c = bl if x == 0 else br if x == cols - 1 else hz_b
            else:
                c = vl if x == 0 else vr if x == cols - 1 else 0x20
            ln.append((c, color))
        out.append(ln)
    return out


