# Colodore palette (C64 colour index -> RGB).
PALETTE = [
    (0x00, 0x00, 0x00), (0xFF, 0xFF, 0xFF), (0x81, 0x33, 0x38),
    (0x75, 0xCE, 0xC8), (0x8E, 0x3C, 0x97), (0x56, 0xAC, 0x4D),
    (0x2E, 0x2C, 0x9B), (0xED, 0xF1, 0x71), (0x8E, 0x50, 0x29),
    (0x55, 0x38, 0x00), (0xC4, 0x6C, 0x71), (0x4A, 0x4A, 0x4A),
    (0x7B, 0x7B, 0x7B), (0xA9, 0xFF, 0x9F), (0x70, 0x6D, 0xEB),
    (0xB2, 0xB2, 0xB2),
]
BLACK, WHITE, RED, CYAN, PURPLE, GREEN, BLUE, YELLOW = range(8)
ORANGE, BROWN, LRED, DGREY, GREY, LGREEN, LBLUE, LGREY = range(8, 16)

# Playfield multicolour: %00 $D021, %01 $D022, %10 $D023, %11 colour RAM.
GAME_PIX = {".": 0, "w": 1, "b": 2, "g": 3}
GAME_COLORS = [BLUE, LBLUE, BROWN, GREEN]
SPR_MC_PIX = {".": 0, "k": 1, "c": 2, "w": 3}
SPR_HR_PIX = {".": 0, "x": 1}
TEXT_PIX = {".": 0, "#": 1}

CH_WATER = 0x00
CH_LAND = 0x08
EDGE_FIRST, EDGE_LAST = 0x10, 0x4F
CRAWFISH_FIRST = 0x50
FX_FIRST, FX_LAST = 0x52, 0x57
FISH_FIRST = 0x58
GIFT_FIRST, GIFT_KINDS = 0x5A, 3
STAMP_FIRST, STAMP_LAST = 0x60, 0xFE   # $FF = transparent marker
STAMP_TRANSPARENT = 0xFF
LOGO_FIRST, LOGO_LAST = 0x80, 0xFF
LOGO_MAX_W, LOGO_MAX_H = 38, 7
SPRITE_BASE_PTR = 96
MAX_SPRITES = 160

STAMP_CLASSES = ["LAND", "WATER", "SHORE_L", "SHORE_R", "SPECIAL"]

HEADER = (
    "; Generated by tools/gfx.py from gfx/*.gfx -- DO NOT EDIT.\n"
    "; Rebuild with: python3 tools/gfx.py  (or: make assets)\n"
)


class GfxError(Exception):
    pass


# ===================================================================
# Source parsing
# ===================================================================

class Block:
    def __init__(self, kind, name, opts, path, lineno):
        self.kind = kind
        self.name = name
        self.opts = opts
        self.path = path
        self.lineno = lineno
        self.lines = []          # raw body lines (comments stripped)

    def where(self):
        return f"{self.path.name}:{self.lineno} @{self.kind} {self.name or ''}"

    def fail(self, msg):
        raise GfxError(f"{self.where()}: {msg}")

    def rows(self):
        """Body as pixel rows with all whitespace removed."""
        out = []
        for ln in self.lines:
            s = re.sub(r"\s+", "", ln)
            if s:
                out.append(s)
        return out

    def token_rows(self):
        """Body as lists of whitespace-separated tokens (blank lines out)."""
        return [ln.split() for ln in self.lines if ln.strip()]

    def opt_int(self, key, default=None):
        if key not in self.opts:
            if default is None:
                self.fail(f"missing option {key}=")
            return default
        return parse_int(self.opts[key])


def parse_int(s):
    s = s.strip()
    if s.startswith("$"):
        return int(s[1:], 16)
    if s.lower().startswith("0x"):
        return int(s[2:], 16)
    return int(s)


def parse_file(path):
    blocks = []
    cur = None
    for lineno, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split(";", 1)[0].rstrip()
        if line.startswith("@"):
            parts = line[1:].split()
            if not parts:
                raise GfxError(f"{path.name}:{lineno}: empty block header")
            kind, name, opts = parts[0], None, {}
            for p in parts[1:]:
                if "=" in p:
                    k, v = p.split("=", 1)
                    opts[k] = v
                elif name is None:
                    name = p
                else:
                    opts[p] = "1"
            cur = Block(kind, name, opts, path, lineno)
            blocks.append(cur)
        elif line.strip():
            if cur is None:
                raise GfxError(f"{path.name}:{lineno}: data outside block")
            cur.lines.append(line)
        elif cur is not None:
            cur.lines.append("")
    return blocks


def grid(block, rows, alphabet, width=None, height=None):
    """Convert pixel rows to a 2D list of values using alphabet."""
    if height is not None and len(rows) != height:
        block.fail(f"expected {height} rows, got {len(rows)}")
    if not rows:
        block.fail("no pixel rows")
    w = len(rows[0])
    for i, r in enumerate(rows):
        if len(r) != w:
            block.fail(f"row {i} has width {len(r)}, expected {w}")
    if width is not None and w != width:
        block.fail(f"expected width {width}, got {w}")
    out = []
    for i, r in enumerate(rows):
        vals = []
        for ch in r:
            if ch not in alphabet:
                block.fail(f"row {i}: bad pixel {ch!r}")
            vals.append(alphabet[ch])
        out.append(vals)
    return out


# ===================================================================
# Byte packing
# ===================================================================

def pack_mc_char(pix):
    """4x8 multicolour pixels (0..3) -> 8 bytes, pixel 0 in bits 7-6."""
    out = []
    for row in pix:
        b = 0
        for v in row:
            b = (b << 2) | v
        out.append(b)
    return bytes(out)


def pack_hr_row(row):
    out = []
    for i in range(0, len(row), 8):
        b = 0
        for v in row[i:i + 8]:
            b = (b << 1) | v
        out.append(b)
    return out


def pack_hr_char(pix):
    return bytes(pack_hr_row(r)[0] for r in pix)


def pack_mc_sprite(pix):
    data = []
    for row in pix:
        for i in range(0, 12, 4):
            b = 0
            for v in row[i:i + 4]:
                b = (b << 2) | v
            data.append(b)
    return bytes(data) + b"\x00"


def pack_hr_sprite(pix):
    data = []
    for row in pix:
        data.extend(pack_hr_row(row))
    return bytes(data) + b"\x00"


def unpack_mc_char(data):
    return [[(b >> (6 - 2 * i)) & 3 for i in range(4)] for b in data]


def unpack_hr_char(data):
    return [[(b >> (7 - i)) & 1 for i in range(8)] for b in data]


def split_chars(block, pix):
    """Split a multicolour image into 4x8 chars, row-major."""
    h, w = len(pix), len(pix[0])
    if w % 4 or h % 8:
        block.fail(f"image {w}x{h} is not a multiple of 4x8")
    chars = []
    for cy in range(h // 8):
        for cx in range(w // 4):
            chars.append([pix[cy * 8 + y][cx * 4:cx * 4 + 4]
                          for y in range(8)])
    return chars, w // 4, h // 8


# ===================================================================
# Bank edge tiles (frozen algorithm, see docs/c64-graphics.md)
# ===================================================================

def edge_pos(lt, d, y):
    return math.floor(lt + d * (2 * y + 1) / 16 + 0.5)


def render_edge(side, lt, d, land):
    """Render one 4x8 edge char. land = CH_LAND pixels (4x8)."""
    W, B, G0 = GAME_PIX["w"], GAME_PIX["b"], GAME_PIX["."]
    pix = []
    for y in range(8):
        e = edge_pos(lt, d, y)
        row = []
        for x in range(4):
            if side == "L":
                if x < e:
                    v = B if x == e - 1 else land[y][x]
                else:
                    v = W if x == e else G0
            else:
                if x >= e:
                    v = B if x == e else land[y][x]
                else:
                    v = W if x == e - 1 else G0
            row.append(v)
        pix.append(row)
    return pix


def lut_index(lt, d):
    return (lt + 2) * 5 + (d + 2)


# ===================================================================
# Compiler state
# ===================================================================

class Gfx:
    def __init__(self):
        self.game = [None] * 256          # 8-byte char data
        self.game_name = {}               # code -> name / comment
        self.game_ids = []                # (name, value, comment)
        self.water_frames = {}            # frame -> 8 chars of pixels
        self.crawfish_frames = {}         # frame -> 2 chars of pixels
        self.fish_frames = {}             # frame -> 2 chars of pixels
        self.gift_frames = {}             # frame -> 6 chars of pixels
        self.land_names = []
        self.edge_lut = {"L": [0] * 50, "R": [0] * 50}
        self.edge_count = {"L": 0, "R": 0}
        self.stamps = []                  # dicts
        self.text = [None] * 256
        self.text_name = {}
        self.text_ids = []
        self.text_color = {}              # code -> preview colour
        self.sprites = []                 # dicts: name, mode, color, pix
        self.sprite_index = {}
        self.anims = []
        self.blocks = []

    # ----------------------------------------------------------------
    def load(self):
        for fn in SOURCE_FILES:
            p = SRC_DIR / fn
            if not p.exists():
                raise GfxError(f"missing source file {p}")
            self.blocks.extend(parse_file(p))

    def set_game_char(self, code, pix, name):
        if not 0 <= code <= 255:
            raise GfxError(f"game char code {code} out of range")
        if self.game[code] is not None:
            raise GfxError(f"game char ${code:02X} defined twice ({name})")
        self.game[code] = pack_mc_char(pix)
        self.game_name[code] = name

    # ----------------------------------------------------------------
    def compile(self):
        b_by_kind = {}
        for b in self.blocks:
            b_by_kind.setdefault(b.kind, []).append(b)
        known = {"chars", "water", "crawfish", "fish", "gifts", "stamp",
                 "tchars", "sprite", "bigsprite", "anim", "logo"}
        for k in b_by_kind:
            if k not in known:
                b_by_kind[k][0].fail(f"unknown block kind @{k}")
        for b in b_by_kind.get("chars", []):
            self.do_chars(b)
        for b in b_by_kind.get("water", []):
            self.do_water(b)
        for b in b_by_kind.get("crawfish", []):
            self.do_crawfish(b)
        for b in b_by_kind.get("fish", []):
            self.do_anim_chars(b, self.fish_frames, 8)
        for b in b_by_kind.get("gifts", []):
            self.do_anim_chars(b, self.gift_frames, 8 * GIFT_KINDS)
        self.finish_water_crawfish()
        self.finish_pickups()
        self.make_edges()
        for b in b_by_kind.get("stamp", []):
            self.do_stamp(b)
        self.finish_game()
        for b in b_by_kind.get("tchars", []):
            self.do_tchars(b)
        for b in b_by_kind.get("logo", []):
            self.do_logo(b)
        self.finish_text()
        for b in self.blocks:
            if b.kind == "sprite":
                self.do_sprite(b)
            elif b.kind == "bigsprite":
                self.do_bigsprite(b)
        for b in b_by_kind.get("anim", []):
            self.do_anim(b)
        if len(self.sprites) > MAX_SPRITES:
            raise GfxError(f"{len(self.sprites)} sprites > {MAX_SPRITES}")

    # ---------------------------------------------------------- chars
    def do_chars(self, b):
        at = b.opt_int("at")
        pix = grid(b, b.rows(), GAME_PIX)
        chars, _, _ = split_chars(b, pix)
        names = b.opts.get("names", "").split(",") if "names" in b.opts \
            else []
        names = [n for n in names if n]
        if names and len(names) != len(chars):
            b.fail(f"{len(names)} names for {len(chars)} chars")
        for i, c in enumerate(chars):
            code = at + i
            nm = names[i] if names else f"{b.name or 'chars'}+{i}"
            self.set_game_char(code, c, nm)
            if names:
                self.game_ids.append((f"CH_{nm}", code, None))
        if at <= CH_LAND < at + len(chars):
            self.land_pix = chars[CH_LAND - at]
            self.land_names = names[CH_LAND - at:] if names else []

    def do_water(self, b):
        f = b.opt_int("frame")
        pix = grid(b, b.rows(), GAME_PIX, width=32, height=8)
        chars, _, _ = split_chars(b, pix)
        if f in self.water_frames:
            b.fail(f"water frame {f} defined twice")
        self.water_frames[f] = chars
        if f == 0 and "names" in b.opts:
            names = b.opts["names"].split(",")
            if len(names) != 8:
                b.fail("water needs 8 names")
            self.water_names = names

    def do_crawfish(self, b):
        f = b.opt_int("frame")
        pix = grid(b, b.rows(), GAME_PIX, width=8, height=8)
        chars, _, _ = split_chars(b, pix)
        if f in self.crawfish_frames:
            b.fail(f"crawfish frame {f} defined twice")
        self.crawfish_frames[f] = chars

    def do_anim_chars(self, b, store, width):
        f = b.opt_int("frame")
        pix = grid(b, b.rows(), GAME_PIX, width=width, height=8)
        chars, _, _ = split_chars(b, pix)
        if f in store:
            b.fail(f"frame {f} defined twice")
        store[f] = chars

    def finish_pickups(self):
        for label, store, first, names in (
                ("fish", self.fish_frames, FISH_FIRST,
                 ["FISH_L", "FISH_R"]),
                ("gift", self.gift_frames, GIFT_FIRST,
                 [f"GIFT{k}_{s}" for k in range(GIFT_KINDS)
                  for s in "LR"])):
            n = len(store)
            if n < 1 or sorted(store) != list(range(n)):
                raise GfxError(f"{label} frames must be 0..n-1")
            for i, c in enumerate(store[0]):
                self.set_game_char(first + i, c, names[i])
                self.game_ids.append((f"CH_{names[i]}", first + i, None))
        self.game_ids.append(("FISH_FRAMES", len(self.fish_frames),
                              "16 bytes per frame"))
        self.game_ids.append(("CH_GIFT_FIRST", GIFT_FIRST, None))
        self.game_ids.append(("GIFT_KINDS", GIFT_KINDS, None))
        self.game_ids.append(("GIFT_FRAMES", len(self.gift_frames),
                              "48 bytes per frame"))

    def finish_water_crawfish(self):
        n = len(self.water_frames)
        if n not in (4, 8) or sorted(self.water_frames) != list(range(n)):
            raise GfxError(f"need 4 or 8 water frames 0..n-1, have "
                           f"{sorted(self.water_frames)}")
        blank = [[0] * 4 for _ in range(8)]
        for f in range(n):
            if self.water_frames[f][0] != blank:
                raise GfxError(f"water frame {f}: char $00 must be blank")
        names = getattr(self, "water_names",
                        ["WATER"] + [f"RIPPLE{i}" for i in range(1, 8)])
        for i, c in enumerate(self.water_frames[0]):
            self.set_game_char(i, c, names[i])
        self.game_ids.append(("CH_WATER", CH_WATER, "plain water"))
        self.game_ids.append(("CH_RIPPLE_FIRST", 1, "ripple/glint chars"))
        self.game_ids.append(("CH_RIPPLE_COUNT", 7, None))
        self.game_ids.append(("WATER_FRAMES", n, "frames in water_anim"))
        n = len(self.crawfish_frames)
        if n < 1 or sorted(self.crawfish_frames) != list(range(n)):
            raise GfxError("crawfish frames must be 0..n-1")
        for i, c in enumerate(self.crawfish_frames[0]):
            self.set_game_char(CRAWFISH_FIRST + i, c,
                               "CRAWFISH_" + "LR"[i])
        self.game_ids.append(("CH_CRAWFISH_L", CRAWFISH_FIRST, None))
        self.game_ids.append(("CH_CRAWFISH_R", CRAWFISH_FIRST + 1, None))
        self.game_ids.append(("CRAWFISH_FRAMES", n, "16 bytes per frame"))

    # ---------------------------------------------------------- edges
    def make_edges(self):
        if self.game[CH_LAND] is None:
            raise GfxError("CH_LAND ($08) not defined")
        land = unpack_mc_char(self.game[CH_LAND])
        water_b = bytes(8)
        if self.game[CH_WATER] != water_b:
            raise GfxError("CH_WATER must be blank water")
        land_b = self.game[CH_LAND]
        code = EDGE_FIRST
        seen = {}
        for side in "LR":
            first = code
            for lt in range(-2, 8):
                for d in range(-2, 3):
                    data = pack_mc_char(render_edge(side, lt, d, land))
                    if data == water_b:
                        c = CH_WATER
                    elif data == land_b:
                        c = CH_LAND
                    elif data in seen:
                        c = seen[data]
                    else:
                        if code > EDGE_LAST:
                            raise GfxError("edge tiles overflow $10-$4F")
                        c = code
                        seen[data] = c
                        self.game[c] = data
                        self.game_name[c] = f"edge {side} lt={lt} d={d}"
                        code += 1
                    self.edge_lut[side][lut_index(lt, d)] = c
            self.edge_count[side] = code - first
            self.game_ids.append((f"CH_EDGE_{side}_FIRST", first, None))
            self.game_ids.append((f"CH_EDGE_{side}_COUNT", code - first,
                                  None))
        self.edge_end = code

    # --------------------------------------------------------- stamps
    def do_stamp(self, b):
        name = b.name
        if not name or not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            b.fail("stamp needs an UPPER_CASE name")
        cls = b.opts.get("class", "LAND")
        if cls not in STAMP_CLASSES:
            b.fail(f"bad class {cls}")
        bg = b.opts.get("bg", "water" if cls == "WATER" else "land")
        alpha = dict(GAME_PIX)
        alpha["-"] = -1
        pix = grid(b, b.rows(), alpha)
        chars, w, h = split_chars(b, pix)
        land = unpack_mc_char(self.game[CH_LAND])
        codes = []
        for c in chars:
            if all(v == -1 for r in c for v in r):
                codes.append(STAMP_TRANSPARENT)
                continue
            res = [[(v if v != -1 else
                     (land[y][x] if bg == "land" else 0))
                    for x, v in enumerate(r)] for y, r in enumerate(c)]
            codes.append(self.alloc_stamp_char(b, pack_mc_char(res)))
        self.stamps.append({"name": name, "class": cls, "w": w, "h": h,
                            "codes": codes, "pix": pix, "bg": bg})

    def alloc_stamp_char(self, b, data):
        # Reuse static chars: plain water, land fill, land variants,
        # earlier stamp chars.  Never reuse animated ripples/crawfish.
        candidates = [CH_WATER] + list(range(CH_LAND, 0x10)) + \
            list(range(STAMP_FIRST, STAMP_LAST + 1))
        for c in candidates:
            if self.game[c] == data:
                return c
        for c in range(STAMP_FIRST, STAMP_LAST + 1):
            if self.game[c] is None:
                self.game[c] = data
                self.game_name[c] = f"stamp {b.name}"
                return c
        b.fail("stamp chars overflow $60-$FE")

    def finish_game(self):
        used = sum(1 for c in range(STAMP_FIRST, 256)
                   if self.game[c] is not None)
        self.stamp_chars_used = used
        nvar = 0
        for c in range(CH_LAND + 1, 0x10):
            if self.game[c] is not None:
                nvar += 1
        self.game_ids.append(("CH_LAND_VAR_FIRST", CH_LAND + 1, None))
        self.game_ids.append(("CH_LAND_VAR_COUNT", nvar, None))
        self.game_ids.append(("CH_STAMP_FIRST", STAMP_FIRST, None))
        self.game_ids.append(("CH_STAMP_TRANSPARENT", STAMP_TRANSPARENT,
                              "stamp cell: keep underlying"))
        for c in range(256):
            if self.game[c] is None:
                self.game[c] = bytes(8)

    # ----------------------------------------------------------- text
    def do_tchars(self, b):
        at = b.opt_int("at")
        names = [n for n in b.opts.get("names", "").split(",") if n]
        rows = b.token_rows()
        if len(rows) % 8:
            b.fail(f"{len(rows)} rows: not a multiple of 8")
        glyphs = []
        for band in range(len(rows) // 8):
            band_rows = rows[band * 8:band * 8 + 8]
            n = len(band_rows[0])
            for r in band_rows:
                if len(r) != n:
                    b.fail(f"band {band}: uneven glyph count")
            for g in range(n):
                glyphs.append(grid(b, [r[g] for r in band_rows],
                                   TEXT_PIX, width=8, height=8))
        if names and len(names) != len(glyphs):
            b.fail(f"{len(names)} names for {len(glyphs)} glyphs")
        color = b.opt_int("color", WHITE)
        for i, gl in enumerate(glyphs):
            code = at + i
            if code > 0x7F:
                b.fail(f"text glyph ${code:02X}: $80-$FF are reserved")
            if self.text[code] is not None:
                b.fail(f"text glyph ${code:02X} defined twice")
            if any(gl[7]):
                b.fail(f"glyph ${code:02X}: row 7 must be empty")
            self.text[code] = pack_hr_char(gl)
            self.text_color[code] = color
            if names:
                self.text_name[code] = names[i]
                self.text_ids.append((f"TX_{names[i]}", code, None))

    def do_logo(self, b):
        """Big title logo: cut into 8x8 cells, dedupe into $80-$FF."""
        if hasattr(self, "logo_map"):
            b.fail("only one @logo block allowed")
        pix = grid(b, b.rows(), TEXT_PIX)
        h, w = len(pix), len(pix[0])
        if w % 8 or h % 8:
            b.fail(f"logo {w}x{h} px is not a multiple of 8x8")
        cw, ch = w // 8, h // 8
        if cw > LOGO_MAX_W or ch > LOGO_MAX_H:
            b.fail(f"logo {cw}x{ch} cells exceeds "
                   f"{LOGO_MAX_W}x{LOGO_MAX_H}")
        space = self.text[0x20] or bytes(8)
        seen, nxt, cmap = {}, LOGO_FIRST, []
        for cy in range(ch):
            for cx in range(cw):
                cell = [pix[cy * 8 + y][cx * 8:cx * 8 + 8]
                        for y in range(8)]
                data = pack_hr_char(cell)
                if data == space:
                    cmap.append(0x20)
                    continue
                if data not in seen:
                    if nxt > LOGO_LAST:
                        b.fail("logo needs more than 128 unique chars")
                    seen[data] = nxt
                    self.text[nxt] = data
                    self.text_name[nxt] = f"logo"
                    nxt += 1
                cmap.append(seen[data])
        self.logo_map, self.logo_w, self.logo_h = cmap, cw, ch
        self.logo_chars = nxt - LOGO_FIRST
        self.logo_pix = pix

    def finish_text(self):
        for c in range(256):
            if self.text[c] is None:
                self.text[c] = bytes(8)
            if c < LOGO_FIRST and self.text[c][7] != 0:
                raise GfxError(f"text glyph ${c:02X}: row 7 not empty")
        used = LOGO_FIRST + getattr(self, "logo_chars", 0)
        for c in range(used, 0x100):
            if any(self.text[c]):
                raise GfxError(f"text glyph ${c:02X} must stay empty")
        if not hasattr(self, "logo_map"):
            raise GfxError("no @logo block (title_logo.gfx)")

    # -------------------------------------------------------- sprites
    def add_sprite(self, b, name, mode, color, pix):
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            b.fail(f"bad sprite name {name}")
        if name in self.sprite_index:
            b.fail(f"sprite {name} defined twice")
        data = pack_mc_sprite(pix) if mode == "mc" else pack_hr_sprite(pix)
        self.sprite_index[name] = len(self.sprites)
        self.sprites.append({"name": name, "mode": mode, "color": color,
                             "pix": pix, "data": data})

    def do_sprite(self, b):
        name = b.name
        mode = "hr" if "hr" in b.opts else "mc"
        color = b.opt_int("color", BROWN if mode == "mc" else WHITE)
        if "mirror" in b.opts:
            src = b.opts["mirror"]
            if src not in self.sprite_index:
                b.fail(f"mirror source {src} not defined earlier")
            s = self.sprites[self.sprite_index[src]]
            pix = [list(reversed(r)) for r in s["pix"]]
            mode = s["mode"]
            if "color" not in b.opts:
                color = s["color"]
        else:
            alpha = SPR_MC_PIX if mode == "mc" else SPR_HR_PIX
            pix = grid(b, b.rows(), alpha, width=12 if mode == "mc"
                       else 24, height=21)
        self.add_sprite(b, name, mode, color, pix)

    def do_bigsprite(self, b):
        names = b.opts["names"].split(",")
        cols, rows = b.opt_int("cols"), b.opt_int("rows")
        if len(names) != cols * rows:
            b.fail("names must list cols*rows sprites")
        color = b.opt_int("color", BROWN)
        pix = grid(b, b.rows(), SPR_MC_PIX, width=12 * cols,
                   height=21 * rows)
        k = 0
        for ry in range(rows):
            for cx in range(cols):
                part = [r[cx * 12:cx * 12 + 12]
                        for r in pix[ry * 21:ry * 21 + 21]]
                self.add_sprite(b, names[k], "mc", color, part)
                k += 1
        self.bigsprites = getattr(self, "bigsprites", [])
        self.bigsprites.append({"name": b.name, "names": names,
                                "cols": cols, "rows": rows})

    def do_anim(self, b):
        frames = b.opts["frames"].split(",")
        for f in frames:
            if f not in self.sprite_index:
                b.fail(f"anim frame {f} is not a sprite")
        self.anims.append({"name": b.name, "frames": frames,
                           "delay": b.opt_int("delay", 120),
                           "bg": b.opts.get("bg", "water"),
                           "expand": b.opt_int("expand", 0)})


