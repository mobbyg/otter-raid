def font_name(c):
    if c < len(FONT_ORDER):
        ch = FONT_ORDER[c]
        if ch == " ":
            return "space"
        if ch in "£↑←":
            return {"£": "pound", "↑": "up arrow",
                    "←": "left arrow"}[ch]
        return f"'{ch}'"
    return ""


