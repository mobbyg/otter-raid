def scr_codes(s):
    out = []
    for ch in s:
        if "A" <= ch <= "Z":
            out.append(ord(ch) - 64)
        elif ch == "@":
            out.append(0)
        elif " " <= ch <= "?":
            out.append(ord(ch))
        else:
            out.append(0x20)
    return out


def tx(g, name):
    for c, n in g.text_name.items():
        if n == name:
            return c
    return 0x20


